#!/usr/bin/env python3
"""gen-tokens.py — generate benchmark token seed data for scenarios S3/S5/S6.

Generates raw opaque tokens + their SHA256 hashes (for DB seeding) and PKCE
pairs, written to fixed output files in the generated/ directory.

Token hashing matches TokenCrypto::hashToken (TokenCrypto.cc:26-37):
  toUpperCase(sha256Hex(rawToken))

Usage:
    python3 gen-tokens.py access  --count 2000
    python3 gen-tokens.py refresh --count 20000
    python3 gen-tokens.py pkce    --count 512
    python3 gen-tokens.py all
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import secrets
import time
import uuid
from pathlib import Path

DEFAULT_ISSUER = "http://localhost:5555"
ACCESS_TOKEN_TTL = 86400
REFRESH_TOKEN_TTL = 2592000


def hash_token(raw: str) -> str:
    """Hash a raw opaque token the same way the server does (TokenCrypto.cc)."""
    return hashlib.sha256(raw.encode()).hexdigest().upper()


def gen_raw_token() -> str:
    return secrets.token_urlsafe(32)


def gen_pkce_pair() -> tuple[str, str]:
    verifier = base64.urlsafe_b64encode(secrets.token_bytes(32)).rstrip(b"=").decode()
    challenge = (
        base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest())
        .rstrip(b"=")
        .decode()
    )
    return verifier, challenge


def esc_sql(s: str) -> str:
    return s.replace("'", "''")


def generate_access_tokens(out_dir: Path, count: int) -> None:
    now = int(time.time())
    expires_at = now + ACCESS_TOKEN_TTL

    raws = [gen_raw_token() for _ in range(count)]
    hashes = [hash_token(r) for r in raws]

    (out_dir / "access_tokens.txt").write_text(
        "".join(raw + "\n" for raw in raws), encoding="utf-8"
    )

    lines = [
        "-- Auto-generated by gen-tokens.py. Do not edit manually.\n",
        f"-- {count} access tokens for benchmark S3/S6.\n",
        f"-- Generated at: {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(now))}\n\n",
        "WITH bench_users AS (\n",
        "    SELECT id, ROW_NUMBER() OVER (ORDER BY username) - 1 AS rn\n",
        "    FROM users WHERE username LIKE 'bench\\_user\\_%'\n",
        "),\n",
        "token_data (idx, token_hash) AS (\n",
        "    VALUES\n",
    ]
    for i, h in enumerate(hashes):
        comma = "," if i < len(hashes) - 1 else ""
        lines.append(f"        ({i}, '{esc_sql(h)}'){comma}\n")
    lines += [
        ")\n",
        "INSERT INTO oauth2_access_tokens\n",
        "    (token, client_id, user_id, scope, expires_at, revoked,\n",
        "     issued_at, issuer, not_before, introspect_count)\n",
        "SELECT td.token_hash, 'backend-svc', bu.id::text, 'openid profile',\n",
        f"    {expires_at}, false, {now}, '{DEFAULT_ISSUER}', {now}, 0\n",
        "FROM token_data td\n",
        "JOIN bench_users bu ON bu.rn = (td.idx % (SELECT COUNT(*) FROM bench_users))\n",
        "ON CONFLICT (token) DO NOTHING;\n",
    ]

    (out_dir / "bench_access_tokens.sql").write_text("".join(lines), encoding="utf-8")
    print(f"[gen-tokens] access: {count} tokens")


def generate_refresh_tokens(out_dir: Path, count: int) -> None:
    now = int(time.time())
    expires_at = now + REFRESH_TOKEN_TTL

    raws = [gen_raw_token() for _ in range(count)]
    hashes = [hash_token(r) for r in raws]
    family_ids = [uuid.uuid4().hex[:64] for _ in range(count)]

    (out_dir / "refresh_tokens.txt").write_text(
        "".join(raw + "\n" for raw in raws), encoding="utf-8"
    )

    lines = [
        "-- Auto-generated by gen-tokens.py. Do not edit manually.\n",
        f"-- {count} refresh tokens for benchmark S5.\n",
        f"-- Generated at: {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(now))}\n",
        "-- Re-seed: prepend TRUNCATE oauth2_refresh_tokens RESTART IDENTITY CASCADE;\n\n",
        "WITH bench_users AS (\n",
        "    SELECT id, ROW_NUMBER() OVER (ORDER BY username) - 1 AS rn\n",
        "    FROM users WHERE username LIKE 'bench\\_user\\_%'\n",
        "),\n",
        "token_data (idx, token_hash, family_id) AS (\n",
        "    VALUES\n",
    ]
    for i, (h, fid) in enumerate(zip(hashes, family_ids)):
        comma = "," if i < len(hashes) - 1 else ""
        lines.append(f"        ({i}, '{esc_sql(h)}', '{esc_sql(fid)}'){comma}\n")
    lines += [
        ")\n",
        "INSERT INTO oauth2_refresh_tokens\n",
        "    (token, access_token, client_id, user_id, scope,\n",
        "     expires_at, revoked, family_id)\n",
        "SELECT td.token_hash, td.token_hash, 'fulla-portal', bu.id::text,\n",
        f"    'openid profile', {expires_at}, false, td.family_id\n",
        "FROM token_data td\n",
        "JOIN bench_users bu ON bu.rn = (td.idx % (SELECT COUNT(*) FROM bench_users))\n",
        "ON CONFLICT (token) DO NOTHING;\n",
    ]

    (out_dir / "bench_refresh_tokens.sql").write_text("".join(lines), encoding="utf-8")
    print(f"[gen-tokens] refresh: {count} tokens")


def generate_pkce_pairs(out_dir: Path, count: int) -> None:
    pairs = [gen_pkce_pair() for _ in range(count)]

    (out_dir / "pkce_pairs.txt").write_text(
        "".join(f"{v},{c}\n" for v, c in pairs), encoding="utf-8"
    )
    print(f"[gen-tokens] pkce: {count} pairs")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("kind", choices=["access", "refresh", "pkce", "all"])
    p.add_argument("--count", type=int, default=None)
    p.add_argument("--at-count", type=int, default=2000)
    p.add_argument("--rt-count", type=int, default=20000)
    p.add_argument("--pkce-count", type=int, default=512)
    args = p.parse_args()

    # Output dir is fixed: sibling 'generated/' under this script. Not user-controlled.
    out_dir = Path(__file__).resolve().parent / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.kind == "access":
        generate_access_tokens(out_dir, args.count or 2000)
    elif args.kind == "refresh":
        generate_refresh_tokens(out_dir, args.count or 20000)
    elif args.kind == "pkce":
        generate_pkce_pairs(out_dir, args.count or 512)
    elif args.kind == "all":
        generate_access_tokens(out_dir, args.at_count)
        generate_refresh_tokens(out_dir, args.rt_count)
        generate_pkce_pairs(out_dir, args.pkce_count)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
